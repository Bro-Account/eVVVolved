#!/bin/bash

# Assembles the Firebird 2.5 (arm64) conversion-helper engine in
# deps/firebird-2.5-arm64 from the native arm64 packages of Debian 8 (jessie,
# archive.debian.org). The result is a self-contained folder that the Linux
# install rules stage next to the program as firebird-2.5/, where the app
# looks up bin/gbak and bin/isql for old-catalog (ODS 11) conversions.
# The folder is NOT part of the git repo (deps/ is ignored, like the Firebird
# 5 runtime fetched by fetch-firebird.sh); run this script once per checkout.
# See deps/firebird-2.5-arm64/README.txt for details. Re-running is safe.

set -euo pipefail

FB_VER="2.5.3.26778.ds4-5+deb8u1"
DEB_ARCH=arm64
MULTIARCH=aarch64-linux-gnu
ICU_VER="52.1-8+deb8u7"
BASE="https://archive.debian.org/debian/pool/main"

# name:subdir:filename:sha256 for every package we need
DEBS=(
  "f/firebird2.5/firebird2.5-classic-common_${FB_VER}_${DEB_ARCH}.deb:8aea10b31d8ec7a60268c57d912a18df0953ceb1aa0c678b0dfce540a1d97760"
  "f/firebird2.5/firebird2.5-classic_${FB_VER}_${DEB_ARCH}.deb:cea1dcb8d3fb0ab061bf01379fe53413d4b83c4171c27793aea98d252d9fd397"
  "f/firebird2.5/firebird2.5-common_${FB_VER}_all.deb:5604383d4dd0efc7e8fa0696c5b10eb607d521ef6d6f1f5e8a761ad431beaa54"
  "f/firebird2.5/firebird2.5-server-common_${FB_VER}_${DEB_ARCH}.deb:51bb783cf0816a2e92030895049507914cf9385751e2f51c6a1657567fdd3fab"
  "f/firebird2.5/libfbembed2.5_${FB_VER}_${DEB_ARCH}.deb:4052fbdaa0f9ea5c67517312e028eb98737cb9fee04b139589a5eb3bd436e6b4"
  "f/firebird2.5/libib-util_${FB_VER}_${DEB_ARCH}.deb:f38ee95cdf98d5d789c77d98423ae1ea95e3420cb0ca00f745b501b0bed4fcf9"
  "i/icu/libicu52_${ICU_VER}_${DEB_ARCH}.deb:54c45f1de677b38d82690b1ee441723e1df66ca8a3f180c29a3d519752b989ac"
)

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DEST="${ROOT}/deps/firebird-2.5-arm64"

if [ -x "${DEST}/bin/gbak" ]; then
  echo "Helper already assembled in ${DEST}"
  exit 0
fi

command -v dpkg >/dev/null || { echo "dpkg is required" >&2; exit 1; }
command -v python3 >/dev/null || { echo "python3 is required" >&2; exit 1; }

TMP="$(mktemp -d)"
trap 'rm -rf "${TMP}"' EXIT

for entry in "${DEBS[@]}"; do
  path="${entry%%:*}"
  sha="${entry##*:}"
  file="${TMP}/$(basename "${path}")"
  url="${BASE}/${path}"
  [ -f "${file}" ] || curl -fL --retry 2 -o "${file}" "${url}"
  echo "${sha}  ${file}" | sha256sum -c - >/dev/null
  dpkg -x "${file}" "${TMP}/root"
done

R="${TMP}/root"
mkdir -p "${DEST}/bin" "${DEST}/lib" "${DEST}/intl"

# binaries; Debian names isql "isql-fb", the app looks up plain "isql"
cp "${R}/usr/bin/gbak" "${DEST}/bin/gbak.real"
cp "${R}/usr/bin/isql-fb" "${DEST}/bin/isql.real"
chmod 755 "${DEST}/bin/"*.real

# libraries: embedded engine (libfbembed), ICU 52 needed by it
cd "${DEST}/lib"
cp "${R}/usr/lib/${MULTIARCH}/libfbembed.so.2.5.3" .
ln -sf libfbembed.so.2.5.3 libfbembed.so.2.5
cp "${R}/usr/lib/${MULTIARCH}/libib_util.so" .
cp "${R}/usr/lib/${MULTIARCH}/libicuuc.so.52.1" .
ln -sf libicuuc.so.52.1 libicuuc.so.52
cp "${R}/usr/lib/${MULTIARCH}/libicudata.so.52.1" .
ln -sf libicudata.so.52.1 libicudata.so.52

cd "${DEST}/intl"
cp "${R}/usr/lib/firebird/2.5/intl/fbintl.so" .
cp "${R}/etc/firebird/2.5/fbintl.conf" .

cd "${DEST}"
cp "${R}/usr/lib/firebird/2.5/firebird.msg" .
cp "${R}/etc/firebird/2.5/firebird.conf" .
cp "${R}/var/lib/firebird/2.5/system/default-security2.fdb" security2.fdb

# The Debian build has the security-database directory compiled in as
# /var/lib/firebird/2.5/system (root-only). Patch the same-length string to
# an unprivileged location in the two binaries and the engine library; the
# wrapper scripts below seed that directory on first use.
python3 - "${DEST}" <<'PYEOF'
import sys
dest = sys.argv[1]
old = b"/var/lib/firebird/2.5/system\x00"
new = b"/tmp/.evvvolved-fb25-sec\x00" + b"\x00" * (len(old) - len(b"/tmp/.evvvolved-fb25-sec\x00"))
assert len(new) == len(old)
for rel in ["bin/gbak.real", "bin/isql.real", "lib/libfbembed.so.2.5.3"]:
    p = dest + "/" + rel
    data = open(p, "rb").read()
    assert data.count(old) > 0, p
    open(p, "wb").write(data.replace(old, new))
PYEOF

for tool in gbak isql; do
cat > "${DEST}/bin/${tool}" <<WRAPEOF
#!/bin/sh
# eVVVolved old-catalog conversion helper: Firebird 2.5 ${tool} (arm64).
# Generated by scripts/fetch-firebird25-arm64.sh; see the folder README.txt.
root=\$(CDPATH= cd -- "\$(dirname -- "\$0")/.." && pwd)
lock="\${TMPDIR:-/tmp}/.evvvolved-fb25-lock"
secd=/tmp/.evvvolved-fb25-sec
if [ ! -w "\$secd/security2.fdb" ]; then
    mkdir -p "\$secd" 2>/dev/null
    cp "\$root/security2.fdb" "\$secd/security2.fdb" 2>/dev/null
    chmod 0777 "\$secd" 2>/dev/null
    chmod 0666 "\$secd/security2.fdb" 2>/dev/null
fi
mkdir -p "\$lock" 2>/dev/null
FIREBIRD="\$root"
FIREBIRD_MSG="\$root"
FIREBIRD_LOCK="\$lock"
LD_LIBRARY_PATH="\$root/lib\${LD_LIBRARY_PATH:+:\$LD_LIBRARY_PATH}"
export FIREBIRD FIREBIRD_MSG FIREBIRD_LOCK LD_LIBRARY_PATH
exec "\$root/bin/${tool}.real" "\$@"
WRAPEOF
chmod 755 "${DEST}/bin/${tool}"
done

cat > "${DEST}/README.txt" <<'DOCEOF'
Firebird 2.5 conversion-helper engine (arm64 / aarch64 Linux)
=============================================================

This folder is the bundled helper engine that eVVVolved uses to convert old
VVV 1.5 catalogs (Firebird ODS 11 files) to the current Firebird 5 format.
It is used in-process: gbak reads and backs up the old catalog file directly
and isql reads the old table row counts; no Firebird server is started.

Source: Debian 8 (jessie), archive.debian.org, Firebird 2.5.3.26778.ds4-5
(+deb8u1), native arm64 packages (firebird2.5-classic-common, -common,
-server-common, libfbembed2.5, libib-util; plus libicu52 52.1-8+deb8u7).
Assembled by scripts/fetch-firebird25-arm64.sh.

Layout:
  bin/gbak, bin/isql   wrapper scripts (set env, seed the security database)
  bin/*.real           the real 2.5 binaries (Debian names isql "isql-fb")
  lib/                 libfbembed.so.2.5 (embedded engine), libib_util.so,
                       ICU 52 (libicuuc, libicudata)
  intl/                character-set/collation module
  firebird.conf        engine configuration
  firebird.msg         engine messages
  security2.fdb        bundled security database (SYSDBA / masterkey)

Two patches were made to the stock Debian files:
- The compiled-in security-database directory /var/lib/firebird/2.5/system
  (root-only) was replaced with /tmp/.evvvolved-fb25-sec in bin/*.real and
  lib/libfbembed.so.2.5.3. The wrapper scripts seed that directory from the
  bundled security2.fdb on first use and keep it world-writable, so every
  account can use the helper (SYSDBA/masterkey, no real users in it).
- The message-file lookup was pointed at this folder with FIREBIRD_MSG
  (the Debian build expects /usr/share/firebird/2.5/ otherwise).

Licenses: Firebird 2.5 is licensed under the IDPL 1.0.1 / IPL
(see licenses/Firebird-5-IDPLicense.txt and Firebird-5-IPLicense.txt in this
distribution - the same licenses as the Firebird 5 runtime), the ICU library
under the ICU license (see licenses/ICU-63-LICENSE.txt). Debian packaging
GNU GPL applies to the Debian-specific build/packaging scripts only; the
upstream engine code is IDPL/IPL. The wrapper scripts in bin/ are released
under the same license as eVVVolved.
DOCEOF

echo "Firebird 2.5 helper assembled in ${DEST}"
echo "Quick check: ${DEST}/bin/gbak -z   (expect: LI-V2.5.3.26778 Firebird 2.5)"
